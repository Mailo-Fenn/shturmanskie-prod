<h2>
    Важнейшим событием в истории марки “Штурманские” без сомнения, стал момент, когда часы взял с собой в первый космический полет Юрий Гагарин.
</h2>
<p>
    12 апреля 1961 года стала знаменательной датой в истории человечества ­ запуск с космодрома Байконур первого пилотируемого космического корабля «Восток». Первый в мире, Советский космонавт Юрий Гагарин пробыл на околоземной орбите 1 час 48 минут и совершил один оборот вокруг Земли. 
</p>