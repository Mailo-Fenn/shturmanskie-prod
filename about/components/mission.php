<h2 class="section-title">
    Миссия марки Штурманские – сопровождать и безотказно служить людям, покоряющим космическое пространство,<br/>
воздушный океан и любые другие стихии – на Земле или в космосе.
</h2>
<p>
    С момента выпуска первых образцов “Штурманских” в 1949 году до наших дней часы конструируются и изготавливаются на производстве, расположенном в самом сердце России ­ Москве, в 10 минут от Кремля. Коллектив компании состоит из лучших часовых специалистов России: конструкторов, технологов, дизайнеров, лучших династий часовых дел мастеров.
</p>
<p>
    На протяжении всей своей полувековой истории марка “Штурманские” уверенно удерживала лидерство среди производителей наручных часов.<br/>
Каждая коллекция часов «Штурманских» – это символ признания успехов советских и российских покорителей новых пространств и стихий.<br/>
<br/>
С годами модели обновлялись, но философия оставалась прежней: часы должны быть точными, понятными и выносливыми. Современные «Штурманские» сохранили дух оригинала — те же узнаваемые черты, та же честность механизма и характер настоящего инструмента. Только технологии стали совершеннее, а материалы — прочнее.

Сегодня «Штурманские» — это не просто часы. Это память о времени, когда человек впервые поднялся выше облаков и шагнул в космос. Это уважение к инженерной мысли и к людям, которые умели мечтать и воплощать мечту в металл, стекло и шестерёнки.

И пока тикает стрелка на циферблате «Штурманских», продолжается история — история мужества, точности и движения вперёд.
</p>